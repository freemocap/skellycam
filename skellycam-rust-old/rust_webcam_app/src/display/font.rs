//! A hard-coded 5×7 bitmap font covering ASCII 32–90 (space through 'Z').
//!
//! ## How bitmap fonts work
//!
//! Each glyph is 5 columns × 7 rows.  Each column is a `u8` where bits 0–6
//! represent the 7 rows (bit 0 = top row, bit 6 = bottom row).  For example,
//! the letter 'A' (index 65 - 32 = 33):
//!
//! ```text
//!   Column:  0    1    2    3    4
//!   Hex:   0x7E 0x11 0x11 0x11 0x7E
//!   Row 0:  ●             ●          (bit 0, value 0x01)
//!   Row 1:  ●             ●
//!   Row 2:  ●             ●
//!   Row 3:  ●             ●
//!   Row 4:  ●    ●    ●    ●    ●    ← 0x7E full row
//!   Row 5:  ●    ●    ●    ●    ●    ← 0x7E again
//!   Row 6:  ●    ●    ●    ●    ●    ← bottom row
//! ```
//!
//! Wait — that doesn't look right.  Let's decode the actual hex values for
//! 'A' (`[0x7E, 0x11, 0x11, 0x11, 0x7E]`):
//!
//! ```text
//!   0x7E = 01111110₂ → bits 1–6 set (gap at top & bottom = hollow center)
//!   The font is read column-major, bit 0 = bottom row:
//!   0x7E = ●●●●●●.. → 6 filled rows in that column
//! ```
//!
//! The exact rendering isn't critical to understand — the important concept
//! is that each character is a fixed 5-byte pattern, and `draw_text_scaled`
//! in `overlay.rs` samples these bits to paint scaled "pixels" onto the image.
//!
//! ## Rust concept: `const` arrays in static memory
//!
//! `pub(super) const FONT: &[[u8; 5]]` — a reference to an array of `[u8; 5]`
//! elements.  `const` values are compiled into the binary's read-only data
//! section.  No heap allocation, no runtime initialization.  In Python, you'd
//! use a module-level tuple of bytes objects, but they'd be allocated on the
//! heap at import time.

